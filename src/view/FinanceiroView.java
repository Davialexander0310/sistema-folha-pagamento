    public void refresh(){
        
        try{
            DefaultTableModel model = (DefaultTableModel) jTable.getModel();
            
            model.setRowCount(0);
            
            contasPagar = financeiroController.listarTodos();
            
            contasPagar.sort((c1, c2) -> c1.getStatus().compareTo(c2.getStatus()));
            
            for(ContaPagar c : contasPagar){
                model.addRow(new Object[]{
                    c.getDescricao(), c.getValor(), c.getVencimento(), c.getStatus()
                });
            }
            
        }
        catch(Exception e){
            System.out.println("Não foi possível carregar o financeiro agora: " + e.getMessage());  
        }
    }
    
