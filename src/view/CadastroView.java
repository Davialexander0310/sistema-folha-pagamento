    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
        try{
            String nome =  txtNome.getText();
            String cargo = txtCargo.getText();
            double salario = Double.parseDouble(txtSalarioBruto.getText());
            
            if (nome.trim().isEmpty() || cargo.trim().isEmpty() || salario <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "Preencha todos os campos corretamente", "Erro", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
            }
            
            Funcionario f = new Funcionario();
            f.setNomeFuncionario(nome);
            f.setCargoFuncionario(cargo);
            f.setSalarioBruto(salario);
            cadastroController.cadastrar(f);
            txtNome.setText("");
            txtCargo.setText("");
            txtSalarioBruto.setText("");
            
            refresh();
        }
        catch(NumberFormatException e){
            javax.swing.JOptionPane.showMessageDialog(this, "Digite um número válido no salário", "Erro", javax.swing.JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnSalvarActionPerformed

